function TT = exp2_transition_age_error(mode)
%EXP2_TRANSITION_AGE_ERROR  Error of the estimated transition age (Table 1).
%
%   TT = exp2_transition_age_error('real')
%
%   Paper item: Table 1 (tab:tau_error), SD of tau_hat - clinical onset
%   in converters and its normal mixture (85 % core, 15 % tail).
%   Inputs : data/<COHORT>_<TR>.csv and data/tau/tau_<COHORT>_<TR>.csv
%   Outputs: results/<mode>/exp2_transition_age_error/
%              tau_error_table.csv   used by exp4 when TAU_SOURCE = 'computed'
%              tau_error_table.tex
%   It also prints the difference with the published values
%   (config.m, TAU_PAPER).
%
%   Authorship: Carlos Platero (UPM), with the collaboration of Claude
%   (Anthropic).

if nargin < 1, mode = 'real'; end
C = config(mode);
out = fullfile(C.resultsDir, 'exp2_transition_age_error');
if ~exist(out, 'dir'), mkdir(out); end

TR = {'CU2MCI', 'MCI2Dem'};
TT = struct('cohort', {}, 'transition', {}, 'n', {}, 'bias', {}, 'sd_classic', {}, ...
            'sd_robust', {}, 'core', {}, 'tail', {}, 'pTail', {});
for c = 1:numel(C.cohorts)
    for t = 1:2
        TT(end+1) = calib_tau_error(C.cohorts{c}, TR{t}, ...
            'dataDir', C.dataDir, 'tauDir', C.tauDir); %#ok<AGROW>
    end
end

% CSV
fid = fopen(fullfile(out, 'tau_error_table.csv'), 'w');
fprintf(fid, 'cohort,transition,n,bias,sd_classic,sd_robust,core,tail,pTail\n');
for k = 1:numel(TT)
    x = TT(k);
    fprintf(fid, '%s,%s,%d,%.6f,%.6f,%.6f,%.6f,%.6f,%.2f\n', x.cohort, x.transition, ...
        x.n, x.bias, x.sd_classic, x.sd_robust, x.core, x.tail, x.pTail);
end
fclose(fid);

% LaTeX
fid = fopen(fullfile(out, 'tau_error_table.tex'), 'w');
fprintf(fid, '%% Auto-generated by exp2_transition_age_error.m\n\\begin{table}[htbp]\n\\centering\n');
fprintf(fid, ['\\caption{Error of the estimated transition age in converters, ' ...
    '$e_i=\\hat{\\tau}_i-$ clinical onset age. Bias corrected by half the visit interval. ' ...
    'SD$_{\\rm rob}$: $1.4826\\times$MAD. Mixture: core (85\\,\\%%) and tail (15\\,\\%%) SDs, ' ...
    'corrected by the visit interval.}\n\\label{tab:tau_error}\n\\small\n']);
fprintf(fid, '\\begin{tabular}{@{}llrrrrrr@{}}\n\\toprule\n');
fprintf(fid, 'Cohort & Transition & $n$ & Bias & SD & SD$_{\\rm rob}$ & Core SD & Tail SD \\\\\n\\midrule\n');
for k = 1:numel(TT)
    x = TT(k);
    fprintf(fid, '%s & %s & %d & %.2f & %.2f & %.2f & %.2f & %.1f \\\\\n', x.cohort, ...
        strrep(x.transition, '2', '$\to$'), x.n, x.bias, x.sd_classic, x.sd_robust, x.core, x.tail);
end
fprintf(fid, '\\bottomrule\n\\end{tabular}\n\\end{table}\n');
fclose(fid);

% Comparison with the published values
fprintf('\n%-6s %-8s %10s %10s %10s %10s\n', 'cohort', 'trans.', 'core', 'core(pap)', 'tail', 'tail(pap)');
for k = 1:numel(TT)
    P = C.TAU_PAPER(strcmp({C.TAU_PAPER.cohort}, TT(k).cohort) & strcmp({C.TAU_PAPER.transition}, TT(k).transition));
    fprintf('%-6s %-8s %10.3f %10.3f %10.3f %10.3f\n', TT(k).cohort, TT(k).transition, ...
        TT(k).core, P.core, TT(k).tail, P.tail);
end
fprintf('Results in %s\n', out);
end
