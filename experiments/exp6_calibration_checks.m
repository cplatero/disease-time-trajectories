function T = exp6_calibration_checks(mode)
%EXP6_CALIBRATION_CHECKS  Two sensitivity checks of the calibrated p-value.
%
%   T = exp6_calibration_checks('real')
%
%   On the 8 comparisons of MEM and EF by amyloid status (2 cohorts x 2
%   transitions x 2 markers), 200 calibrated replicates each:
%     check 1 (noTau) : delta_i = 0, so only the design bias of the
%                       estimator acts;
%     check 2 (robust): subject locations not clipped and null curve flat
%                       2 years beyond the analysis window.
%   Paper item: Table S10, the two checks (Sec. 4.2.3),
%   sim_checks_summary.csv / .tex.
%   Needs exp3 and exp4. Outputs: results/<mode>/exp6_calibration_checks/
%
%   Converted from run_checks.m (4 Nov 2026).
%
%   Authorship: Carlos Platero (UPM), with the collaboration of Claude
%   (Anthropic).

if nargin < 1, mode = 'real'; end
C = config(mode);
in3 = fullfile(C.resultsDir, 'exp3_bandwidth');
in4 = fullfile(C.resultsDir, 'exp4_calibrated_pvalues');
out = fullfile(C.resultsDir, 'exp6_calibration_checks');
if ~exist(out, 'dir'), mkdir(out); end
if strcmp(C.TAU_SOURCE, 'paper')
    tauTable = C.TAU_PAPER;
else
    R = readtable(fullfile(C.resultsDir, 'exp2_transition_age_error', 'tau_error_table.csv'), 'TextType', 'string');
    tauTable = struct('cohort', cellstr(R.cohort)', 'transition', cellstr(R.transition)', ...
                      'core', num2cell(R.core)', 'tail', num2cell(R.tail)', 'pTail', num2cell(R.pTail)');
end

%% 1. Calibration files restricted to the 8 comparisons
for c = 1:numel(C.cohorts)
    co = C.cohorts{c};
    K = readtable(fullfile(in3, sprintf('calib_%s.csv', co)), 'TextType', 'string');
    keep = K.analysis == "A" & ismember(K.var, {'MEM', 'EF'});
    fprintf('%s: %d comparisons kept\n', co, sum(keep));      % 4 per cohort
    writetable(K(keep, :), fullfile(out, sprintf('calib_%s_8.csv', co)));
end

%% 2. The two checks, per cohort
for c = 1:numel(C.cohorts)
    co  = C.cohorts{c};
    obs = {fullfile(in3, sprintf('bw_sensitivity_%s.csv', co)), ...
           fullfile(in3, sprintf('bw_sensitivity_%s_ll.csv', co))};
    common = {'design', 'calibrated', 'calibFiles', {fullfile(out, sprintf('calib_%s_8.csv', co))}, ...
              'obsFiles', obs, 'tauTable', tauTable, 'nRepsCal', C.N_REPS_CHECK, ...
              'nPerm', C.N_PERM_CAL, 'bw', C.BW, 'seed', C.SEED, 'bPlots', false};
    sim_framework(common{:}, 'calNoTau', true,  'outDir', fullfile(out, sprintf('sim_check_noTau_%s', co)));
    sim_framework(common{:}, 'calRobust', true, 'outDir', fullfile(out, sprintf('sim_check_robust_%s', co)));
end

%% 3. Summary: main run vs. the two checks
rd = @(f) readtable(f, 'TextType', 'string');
S = struct('comparison', {}, 'estimator', {}, 'typeI_main', {}, 'typeI_noTau', {}, ...
           'typeI_robust', {}, 'pCal_main', {}, 'pCal_robust', {});
for c = 1:numel(C.cohorts)
    co = C.cohorts{c};
    M = rd(fullfile(in4, sprintf('sim_out_%s', co), 'sim_results.csv'));
    N = rd(fullfile(out, sprintf('sim_check_noTau_%s', co), 'sim_results.csv'));
    B = rd(fullfile(out, sprintf('sim_check_robust_%s', co), 'sim_results.csv'));
    for k = 1:height(N)
        m = M.scenario == N.scenario(k) & M.estimator == N.estimator(k);
        b = B.scenario == N.scenario(k) & B.estimator == N.estimator(k);
        e = char(N.estimator(k));
        if ~ismember(e, {sprintf('swll_bw%g', C.BW), sprintf('sw_bw%g', C.BW), 'poly'}), continue; end
        S(end+1) = struct('comparison', char(N.scenario(k)), 'estimator', e, ...
            'typeI_main', M.reject(m), 'typeI_noTau', N.reject(k), 'typeI_robust', B.reject(b), ...
            'pCal_main', M.pCal(m), 'pCal_robust', B.pCal(b)); %#ok<AGROW>
    end
end
T = struct2table(S);
writetable(T, fullfile(out, 'sim_checks_summary.csv'));
write_tex(T, fullfile(out, 'sim_checks_summary.tex'), C);
disp(T)
end


function write_tex(T, file, C)
ename = containers.Map({sprintf('swll_bw%g', C.BW), sprintf('sw_bw%g', C.BW), 'poly'}, ...
    {'local-linear \textit{sw}-LOESS', 'local-constant \textit{sw}-LOESS', 'global polynomial'});
fid = fopen(file, 'w');
fprintf(fid, '%% Auto-generated by exp6_calibration_checks.m\n\\begin{table}[htbp]\n\\centering\n');
fprintf(fid, ['\\caption{Sensitivity checks of the calibrated simulation, MEM and EF by amyloid status. ' ...
    'Type~I: rejection rate under the calibrated null in the main run, without transition-age error ' ...
    '($\\delta_i=0$) and with the robust null (locations not clipped, flat curve beyond the window). ' ...
    '$p_{\\rm cal}$: main run and robust null. %d replicates per check.}\n' ...
    '\\label{tab:S_sim_checks}\n\\scriptsize\n'], C.N_REPS_CHECK);
fprintf(fid, '\\begin{tabular}{@{}lllrrrrr@{}}\n\\toprule\n');
fprintf(fid, ['Comparison & Marker & Estimator & Type~I & Type~I ($\\delta_i=0$) & Type~I (robust) ' ...
    '& $p_{\\rm cal}$ & $p_{\\rm cal}$ (robust) \\\\\n\\midrule\n']);
for k = 1:height(T)
    parts = strsplit(char(T.comparison{k}), '|');
    fprintf(fid, '%s %s & %s & %s & %.2f & %.2f & %.2f & %s & %s \\\\\n', parts{1}, ...
        strrep(parts{2}, '2', '$\to$'), parts{4}, ename(char(T.estimator{k})), T.typeI_main(k), ...
        T.typeI_noTau(k), T.typeI_robust(k), f3(T.pCal_main(k)), f3(T.pCal_robust(k)));
end
fprintf(fid, '\\bottomrule\n\\end{tabular}\n\\end{table}\n');
fclose(fid);
end


function s = f3(p)
if isnan(p), s = '---'; else, s = sprintf('%.3f', p); end
end
